  String translate(String key) {
    return _values[locale.languageCode]?[key] ?? _values['en']?[key] ?? key;
  }

  String translateLiteral(String input) {
    if (locale.languageCode != 'ar') return input;

    final exact = _literalArabic[input];
    if (exact != null) return exact;

    // Dynamic strings used throughout the UI.
    var match = RegExp(r'^Passenger (\d+)$').firstMatch(input);
    if (match != null) return 'المسافر ${match.group(1)}';

    match = RegExp(r'^Seat (.+)$').firstMatch(input);
    if (match != null) return 'المقعد ${match.group(1)}';

    match = RegExp(r'^Day (\d+)$').firstMatch(input);
    if (match != null) return 'اليوم ${match.group(1)}';

    match = RegExp(r'^(\d+) places$').firstMatch(input);
    if (match != null) return '${match.group(1)} أماكن';

    match = RegExp(r'^(\d+) passenger(?:s)?$').firstMatch(input);
    if (match != null) return '${match.group(1)} مسافر';

    match = RegExp(r'^(\d+) Traveler(?:s)?$').firstMatch(input);
    if (match != null) return '${match.group(1)} مسافر';

    match = RegExp(r'^Reference: (.+)$').firstMatch(input);
    if (match != null) return 'المرجع: ${match.group(1)}';

    match = RegExp(r'^Seats: (.+)$').firstMatch(input);
    if (match != null) return 'المقاعد: ${match.group(1)}';

    match = RegExp(r'^(.+) km away$').firstMatch(input);
    if (match != null) return 'يبعد ${match.group(1)} كم';

    match = RegExp(r'^(.+) min$').firstMatch(input);
    if (match != null) return '${match.group(1)} دقيقة';

    // Short reusable phrases inside dynamic copy.
    return input
        .replaceAll('places', 'أماكن')
        .replaceAll('Traveler', 'مسافر')
        .replaceAll('Travelers', 'مسافرون')
        .replaceAll('passengers', 'مسافرين')
        .replaceAll('passenger', 'مسافر')
        .replaceAll('Direct', 'مباشر')
        .replaceAll('Current Location', 'الموقع الحالي');
  }
